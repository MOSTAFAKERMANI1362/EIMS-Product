-- EIMS S1b-2 / V003
-- G04 Assessment + frozen governance/profile snapshots + committee votes
-- Owner schema: EIMS_OWNER
-- Runtime account: EIMS_APP

-- Created when the last required assignment completes (mirrors G04AssessmentEnvelope); voting/final decision fields are added in S2d.
CREATE TABLE EIMS_G04_ASSESSMENT (
    ID                         VARCHAR2(100 CHAR) NOT NULL,
    PLAN_ID                    VARCHAR2(100 CHAR) NOT NULL,
    IDEA_ID                    VARCHAR2(128 CHAR) NOT NULL,
    IDEA_VERSION               NUMBER(19)         NOT NULL,
    PLAN_VERSION               NUMBER(10)         NOT NULL,
    STATE                      VARCHAR2(60 CHAR)  NOT NULL,
    REQUIRED_SNAPSHOT_SHA256   VARCHAR2(128 CHAR) NOT NULL,
    CORRELATION_ID             VARCHAR2(128 CHAR) NOT NULL,
    DECISION_ROUTE             VARCHAR2(120 CHAR),
    DECISION_ROUTE_KIND        VARCHAR2(60 CHAR),
    DECISION_METHOD            VARCHAR2(60 CHAR),
    GOVERNANCE_PROFILE_ID      VARCHAR2(120 CHAR),
    GOVERNANCE_PROFILE_VERSION VARCHAR2(60 CHAR),
    DECISION_VERSION           NUMBER(10) DEFAULT 0 NOT NULL,
    ENTITY_VERSION             NUMBER(10) DEFAULT 1 NOT NULL,
    CREATED_AT                 TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UPDATED_AT                 TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_G04_ASSESSMENT PRIMARY KEY (ID),
    CONSTRAINT UQ_G04_ASSESS_PLAN UNIQUE (PLAN_ID),
    CONSTRAINT FK_G04_ASSESS_PLAN FOREIGN KEY (PLAN_ID) REFERENCES EIMS_EVALUATION_PLAN (ID),
    CONSTRAINT CK_G04_ASSESS_IDEA_VERSION CHECK (IDEA_VERSION >= 1),
    CONSTRAINT CK_G04_ASSESS_PLAN_VERSION CHECK (PLAN_VERSION >= 1),
    CONSTRAINT CK_G04_ASSESS_DECISION_VER CHECK (DECISION_VERSION >= 0),
    CONSTRAINT CK_G04_ASSESS_VERSION CHECK (ENTITY_VERSION >= 1)
);
CREATE INDEX IX_G04_ASSESS_IDEA ON EIMS_G04_ASSESSMENT (IDEA_ID, IDEA_VERSION);
CREATE INDEX IX_G04_ASSESS_STATE ON EIMS_G04_ASSESSMENT (STATE, DECISION_ROUTE);

-- Frozen committee composition + governance profile, written with the first vote (mirrors G04CommitteeSnapshotEnvelope).
CREATE TABLE EIMS_G04_COMMITTEE_SNAPSHOT (
    ID                         VARCHAR2(100 CHAR) NOT NULL,
    ASSESSMENT_ID              VARCHAR2(100 CHAR) NOT NULL,
    IDEA_ID                    VARCHAR2(128 CHAR) NOT NULL,
    IDEA_VERSION               NUMBER(19)         NOT NULL,
    SCOPE_CODE                 VARCHAR2(128 CHAR) NOT NULL,
    DECISION_ROUTE             VARCHAR2(120 CHAR) NOT NULL,
    GOVERNANCE_PROFILE_ID      VARCHAR2(120 CHAR) NOT NULL,
    GOVERNANCE_PROFILE_VERSION VARCHAR2(60 CHAR)  NOT NULL,
    QUORUM_REQUIRED            NUMBER(10)         NOT NULL,
    VOTE_RULE                  VARCHAR2(60 CHAR)  NOT NULL,
    CHAIR_PERSON_ID            VARCHAR2(64 CHAR)  NOT NULL,
    APPROVAL_AUTHORITY         VARCHAR2(120 CHAR),
    APPROVAL_REF               VARCHAR2(200 CHAR),
    MEMBERS_JSON               CLOB               NOT NULL,
    CORRELATION_ID             VARCHAR2(128 CHAR) NOT NULL,
    CREATED_AT                 TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_G04_COMMITTEE_SNAPSHOT PRIMARY KEY (ID),
    CONSTRAINT UQ_G04_COMMITTEE_SNAP_ASSESS UNIQUE (ASSESSMENT_ID),
    CONSTRAINT FK_G04_COMMITTEE_SNAP_ASSESS FOREIGN KEY (ASSESSMENT_ID) REFERENCES EIMS_G04_ASSESSMENT (ID),
    CONSTRAINT CK_G04_COMMITTEE_SNAP_QUORUM CHECK (QUORUM_REQUIRED >= 1),
    CONSTRAINT CK_G04_COMMITTEE_SNAP_JSON CHECK (MEMBERS_JSON IS JSON)
);

CREATE OR REPLACE TRIGGER TRG_G04_COMMITTEE_SNAP_IMMUTABLE
BEFORE UPDATE OR DELETE ON EIMS_G04_COMMITTEE_SNAPSHOT
FOR EACH ROW
BEGIN
    RAISE_APPLICATION_ERROR(-20041, 'G04 committee snapshot is immutable');
END;
/

-- Mutable voting state; COMMITTEE_VERSION is the optimistic-concurrency token (mirrors G04CommitteeStateEnvelope).
CREATE TABLE EIMS_G04_COMMITTEE_STATE (
    ASSESSMENT_ID           VARCHAR2(100 CHAR) NOT NULL,
    SNAPSHOT_ID             VARCHAR2(100 CHAR) NOT NULL,
    COMMITTEE_VERSION       NUMBER(10)         NOT NULL,
    VOTING_STAGE_STATE      VARCHAR2(30 CHAR)  NOT NULL,
    QUORUM_REACHED          NUMBER(1)          NOT NULL,
    APPROVAL_RULE_SATISFIED NUMBER(1)          NOT NULL,
    EFFECTIVE_VOTE_COUNT    NUMBER(10)         NOT NULL,
    APPROVE_COUNT           NUMBER(10)         NOT NULL,
    REJECT_COUNT            NUMBER(10)         NOT NULL,
    CORRELATION_ID          VARCHAR2(128 CHAR) NOT NULL,
    COMPLETED_AT            TIMESTAMP(6) WITH TIME ZONE,
    UPDATED_AT              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_G04_COMMITTEE_STATE PRIMARY KEY (ASSESSMENT_ID),
    CONSTRAINT FK_G04_COMMITTEE_STATE_ASSESS FOREIGN KEY (ASSESSMENT_ID) REFERENCES EIMS_G04_ASSESSMENT (ID),
    CONSTRAINT FK_G04_COMMITTEE_STATE_SNAP FOREIGN KEY (SNAPSHOT_ID) REFERENCES EIMS_G04_COMMITTEE_SNAPSHOT (ID),
    CONSTRAINT CK_G04_COMMITTEE_STATE_VER CHECK (COMMITTEE_VERSION >= 1),
    CONSTRAINT CK_G04_COMMITTEE_STATE_FLAGS CHECK (QUORUM_REACHED IN (0,1) AND APPROVAL_RULE_SATISFIED IN (0,1)),
    CONSTRAINT CK_G04_COMMITTEE_STATE_COUNTS CHECK (EFFECTIVE_VOTE_COUNT >= 0 AND APPROVE_COUNT >= 0 AND REJECT_COUNT >= 0)
);

-- Append-only history of every vote (mirrors G04VoteRevisionEnvelope).
CREATE TABLE EIMS_G04_VOTE_REVISION (
    ID                      VARCHAR2(100 CHAR) NOT NULL,
    ASSESSMENT_ID           VARCHAR2(100 CHAR) NOT NULL,
    SNAPSHOT_ID             VARCHAR2(100 CHAR) NOT NULL,
    COMMITTEE_VERSION       NUMBER(10)         NOT NULL,
    PERSON_ID               VARCHAR2(64 CHAR)  NOT NULL,
    AUTHORITY_ASSIGNMENT_ID VARCHAR2(128 CHAR) NOT NULL,
    VOTE                    VARCHAR2(16 CHAR)  NOT NULL,
    NOTE                    VARCHAR2(4000 CHAR) NOT NULL,
    REVISION_NUMBER         NUMBER(10)         NOT NULL,
    SUPERSEDES_REVISION_ID  VARCHAR2(100 CHAR),
    CORRELATION_ID          VARCHAR2(128 CHAR) NOT NULL,
    CREATED_AT              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_G04_VOTE_REVISION PRIMARY KEY (ID),
    CONSTRAINT UQ_G04_VOTE_REV_PERSON UNIQUE (ASSESSMENT_ID, PERSON_ID, REVISION_NUMBER),
    CONSTRAINT FK_G04_VOTE_REV_ASSESS FOREIGN KEY (ASSESSMENT_ID) REFERENCES EIMS_G04_ASSESSMENT (ID),
    CONSTRAINT FK_G04_VOTE_REV_SNAP FOREIGN KEY (SNAPSHOT_ID) REFERENCES EIMS_G04_COMMITTEE_SNAPSHOT (ID),
    CONSTRAINT FK_G04_VOTE_REV_SUPERSEDES FOREIGN KEY (SUPERSEDES_REVISION_ID) REFERENCES EIMS_G04_VOTE_REVISION (ID),
    CONSTRAINT CK_G04_VOTE_REV_VOTE CHECK (VOTE IN ('APPROVE','REJECT')),
    CONSTRAINT CK_G04_VOTE_REV_NUMBER CHECK (REVISION_NUMBER >= 1),
    CONSTRAINT CK_G04_VOTE_REV_VERSION CHECK (COMMITTEE_VERSION >= 1)
);
CREATE INDEX IX_G04_VOTE_REV_ASSESS ON EIMS_G04_VOTE_REVISION (ASSESSMENT_ID, PERSON_ID);

CREATE OR REPLACE TRIGGER TRG_G04_VOTE_REV_IMMUTABLE
BEFORE UPDATE OR DELETE ON EIMS_G04_VOTE_REVISION
FOR EACH ROW
BEGIN
    RAISE_APPLICATION_ERROR(-20042, 'G04 vote revision is append-only');
END;
/

-- Current effective vote per member (mirrors G04EffectiveVoteEnvelope).
CREATE TABLE EIMS_G04_EFFECTIVE_VOTE (
    ASSESSMENT_ID    VARCHAR2(100 CHAR) NOT NULL,
    PERSON_ID        VARCHAR2(64 CHAR)  NOT NULL,
    VOTE_REVISION_ID VARCHAR2(100 CHAR) NOT NULL,
    VOTE             VARCHAR2(16 CHAR)  NOT NULL,
    REVISION_NUMBER  NUMBER(10)         NOT NULL,
    UPDATED_AT       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_G04_EFFECTIVE_VOTE PRIMARY KEY (ASSESSMENT_ID, PERSON_ID),
    CONSTRAINT FK_G04_EFFECTIVE_VOTE_ASSESS FOREIGN KEY (ASSESSMENT_ID) REFERENCES EIMS_G04_ASSESSMENT (ID),
    CONSTRAINT FK_G04_EFFECTIVE_VOTE_REV FOREIGN KEY (VOTE_REVISION_ID) REFERENCES EIMS_G04_VOTE_REVISION (ID),
    CONSTRAINT CK_G04_EFFECTIVE_VOTE_VOTE CHECK (VOTE IN ('APPROVE','REJECT')),
    CONSTRAINT CK_G04_EFFECTIVE_VOTE_NUMBER CHECK (REVISION_NUMBER >= 1)
);

-- Immutable final-decision evidence, one per assessment (mirrors G04FinalDecisionEvidenceEnvelope).
-- Provenance fields are NOT NULL (evidence must be complete); free-text fields are nullable (Oracle: '' = NULL, read back as '').
CREATE TABLE EIMS_G04_FINAL_DECISION (
    ID                             VARCHAR2(100 CHAR) NOT NULL,
    ASSESSMENT_ID                  VARCHAR2(100 CHAR) NOT NULL,
    PLAN_ID                        VARCHAR2(100 CHAR) NOT NULL,
    IDEA_ID                        VARCHAR2(128 CHAR) NOT NULL,
    IDEA_REVISION_BEFORE           NUMBER(19)         NOT NULL,
    IDEA_REVISION_AFTER            NUMBER(19)         NOT NULL,
    STATE_MUTATION_BEFORE          NUMBER(19)         NOT NULL,
    STATE_MUTATION_AFTER           NUMBER(19)         NOT NULL,
    DECISION_VERSION_BEFORE        NUMBER(10)         NOT NULL,
    DECISION_VERSION_AFTER         NUMBER(10)         NOT NULL,
    OUTCOME                        VARCHAR2(60 CHAR)  NOT NULL,
    REASON_CODE                    VARCHAR2(120 CHAR) NOT NULL,
    DECISION_COMMENT               CLOB,
    REVIEW_DATE                    TIMESTAMP(6) WITH TIME ZONE,
    PERSON_ID                      VARCHAR2(64 CHAR)  NOT NULL,
    AUTHORITY_ASSIGNMENT_ID        VARCHAR2(128 CHAR) NOT NULL,
    NETWORK_IDENTITY               VARCHAR2(256 CHAR) NOT NULL,
    IDENTITY_SOURCE                VARCHAR2(64 CHAR)  NOT NULL,
    DECISION_ROUTE                 VARCHAR2(120 CHAR) NOT NULL,
    DECISION_ROUTE_KIND            VARCHAR2(60 CHAR)  NOT NULL,
    DECISION_METHOD                VARCHAR2(60 CHAR)  NOT NULL,
    GOVERNANCE_PROFILE_ID          VARCHAR2(120 CHAR) NOT NULL,
    GOVERNANCE_PROFILE_VERSION     VARCHAR2(60 CHAR)  NOT NULL,
    DECISION_PROFILE_ID            VARCHAR2(120 CHAR) NOT NULL,
    DECISION_PROFILE_VERSION       VARCHAR2(60 CHAR)  NOT NULL,
    PROFILE_SNAPSHOT_JSON          CLOB,
    PROFILE_SNAPSHOT_SHA256        VARCHAR2(128 CHAR) NOT NULL,
    RULE_SET                       VARCHAR2(64 CHAR)  NOT NULL,
    HARD_CONDITION_MAPPING_VERSION VARCHAR2(60 CHAR)  NOT NULL,
    GATE_SCORE                     NUMBER(10)         NOT NULL,
    DATA_READINESS                 NUMBER(10)         NOT NULL,
    RULE_CHECK_RESULTS             CLOB,
    SPECIALIST_OUTCOME_SUMMARY     CLOB,
    COMMITTEE_SNAPSHOT_ID          VARCHAR2(100 CHAR),
    COMMITTEE_VERSION              NUMBER(10),
    COMMITTEE_STAGE_STATE          VARCHAR2(30 CHAR),
    COMMITTEE_APPROVAL_SATISFIED   NUMBER(1),
    SOD_RESULT                     VARCHAR2(60 CHAR)  NOT NULL,
    SOD_EXCEPTION_POLICY           VARCHAR2(200 CHAR),
    DECIDED_AT                     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CORRELATION_ID                 VARCHAR2(128 CHAR) NOT NULL,
    CONSTRAINT PK_G04_FINAL_DECISION PRIMARY KEY (ID),
    CONSTRAINT UQ_G04_FINAL_DECISION_ASSESS UNIQUE (ASSESSMENT_ID),
    CONSTRAINT FK_G04_FINAL_DEC_ASSESS FOREIGN KEY (ASSESSMENT_ID) REFERENCES EIMS_G04_ASSESSMENT (ID),
    CONSTRAINT FK_G04_FINAL_DEC_PLAN FOREIGN KEY (PLAN_ID) REFERENCES EIMS_EVALUATION_PLAN (ID),
    CONSTRAINT FK_G04_FINAL_DEC_COMMITTEE FOREIGN KEY (COMMITTEE_SNAPSHOT_ID) REFERENCES EIMS_G04_COMMITTEE_SNAPSHOT (ID),
    CONSTRAINT CK_G04_FINAL_DEC_APPROVAL CHECK (COMMITTEE_APPROVAL_SATISFIED IN (0,1)),
    CONSTRAINT CK_G04_FINAL_DEC_JSON CHECK (PROFILE_SNAPSHOT_JSON IS JSON)
);
CREATE INDEX IX_G04_FINAL_DEC_IDEA ON EIMS_G04_FINAL_DECISION (IDEA_ID, IDEA_REVISION_AFTER);

CREATE OR REPLACE TRIGGER TRG_G04_FINAL_DEC_IMMUTABLE
BEFORE UPDATE OR DELETE ON EIMS_G04_FINAL_DECISION
FOR EACH ROW
BEGIN
    RAISE_APPLICATION_ERROR(-20051, 'G04 final decision evidence is immutable');
END;
