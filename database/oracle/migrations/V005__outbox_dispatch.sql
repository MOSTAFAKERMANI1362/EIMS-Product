-- EIMS S3 / ACR-S3: outbox dispatcher support (claim token + lease). Run as EIMS_OWNER.
-- DISPATCH_STATUS stays PENDING|SENT|FAILED (FAILED = dead-letter, blocks its aggregate until requeued); retries stay PENDING with NEXT_ATTEMPT_AT.
ALTER TABLE EIMS_OUTBOX ADD (
    CLAIM_TOKEN   VARCHAR2(100 CHAR),
    CLAIMED_UNTIL TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX IX_EIMS_OUTBOX_READY   ON EIMS_OUTBOX (DISPATCH_STATUS, NEXT_ATTEMPT_AT, OUTBOX_SEQ);
CREATE INDEX IX_EIMS_OUTBOX_AGG_SEQ ON EIMS_OUTBOX (AGGREGATE_ID, OUTBOX_SEQ);
CREATE INDEX IX_EIMS_OUTBOX_TOKEN   ON EIMS_OUTBOX (CLAIM_TOKEN);
