-- EIMS S1b-1 — Evaluation Core
-- Scope: Evaluation Plan + Assignment + immutable Evaluation Snapshot
-- Run as EIMS_OWNER inside FREEPDB1.
-- No UI-specific fields are persisted here unless they carry domain meaning.

CREATE TABLE EIMS_EVALUATION_PLAN (
    ID                  VARCHAR2(100 CHAR) NOT NULL,
    IDEA_ID             VARCHAR2(100 CHAR) NOT NULL,
    IDEA_VERSION        NUMBER(10) NOT NULL,
    STATUS              VARCHAR2(30 CHAR) NOT NULL,
    ENTITY_VERSION             NUMBER(10) DEFAULT 1 NOT NULL,
    DECISION_ROUTE      VARCHAR2(60 CHAR),
    RULE_SET            VARCHAR2(120 CHAR),
    PASSPORT_SNAPSHOT   CLOB,
    CREATED_AT          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    FROZEN_AT           TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT CK_EVAL_PLAN_STATUS
        CHECK (STATUS IN ('ACTIVE','SUPERSEDED','COMPLETED','CANCELLED')),
    CONSTRAINT CK_EVAL_PLAN_VERSION
        CHECK (ENTITY_VERSION >= 1),
    CONSTRAINT CK_EVAL_PLAN_IDEA_VERSION
        CHECK (IDEA_VERSION >= 1),
    CONSTRAINT CK_EVAL_PLAN_PASSPORT_JSON
        CHECK (PASSPORT_SNAPSHOT IS JSON),
    CONSTRAINT UQ_EVAL_PLAN_IDEA_VERSION
        UNIQUE (IDEA_ID, IDEA_VERSION),
    CONSTRAINT PK_EVALUATION_PLAN PRIMARY KEY (ID)
);

CREATE INDEX IX_EVAL_PLAN_IDEA_STATUS
    ON EIMS_EVALUATION_PLAN (IDEA_ID, STATUS);

CREATE TABLE EIMS_EVALUATION_ASSIGNMENT (
    ID                  VARCHAR2(100 CHAR) NOT NULL,
    PLAN_ID             VARCHAR2(100 CHAR) NOT NULL,
    ROLE_CODE            VARCHAR2(60 CHAR) NOT NULL,
    ROLE_LABEL           VARCHAR2(200 CHAR),
    REASON              VARCHAR2(1000 CHAR),
    REQUIRED_FLAG       NUMBER(1) DEFAULT 1 NOT NULL,
    STATUS              VARCHAR2(30 CHAR) NOT NULL,
    PERSON_ID           VARCHAR2(100 CHAR),
    OUTCOME             VARCHAR2(100 CHAR),
    SCORE               NUMBER(12,4),
    EVIDENCE             CLOB,
    COMMENT_TEXT        CLOB,
    REASON_TEXT         CLOB,
    COMPLETED_AT        TIMESTAMP(6) WITH TIME ZONE,
    COMPLETED_BY_ROLE   VARCHAR2(60 CHAR),
    ENTITY_VERSION             NUMBER(10) DEFAULT 1 NOT NULL,
    CREATED_AT          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_EVAL_ASSIGN_PLAN
        FOREIGN KEY (PLAN_ID) REFERENCES EIMS_EVALUATION_PLAN(ID),
    CONSTRAINT CK_EVAL_ASSIGN_REQUIRED
        CHECK (REQUIRED_FLAG IN (0,1)),
    CONSTRAINT CK_EVAL_ASSIGN_STATUS
        CHECK (STATUS IN ('PENDING','ACCEPTED','IN_PROGRESS','COMPLETED','CANCELLED')),
    CONSTRAINT CK_EVAL_ASSIGN_VERSION
        CHECK (ENTITY_VERSION >= 1),
    CONSTRAINT PK_EVALUATION_ASSIGNMENT PRIMARY KEY (ID)
);

CREATE INDEX IX_EVAL_ASSIGN_PLAN_STATUS
    ON EIMS_EVALUATION_ASSIGNMENT (PLAN_ID, STATUS);

CREATE INDEX IX_EVAL_ASSIGN_PERSON_STATUS
    ON EIMS_EVALUATION_ASSIGNMENT (PERSON_ID, STATUS);

CREATE TABLE EIMS_EVALUATION_SNAPSHOT (
    ID                  VARCHAR2(100 CHAR) NOT NULL,
    PLAN_ID             VARCHAR2(100 CHAR) NOT NULL,
    IDEA_ID             VARCHAR2(100 CHAR) NOT NULL,
    IDEA_VERSION        NUMBER(10) NOT NULL,
    SNAPSHOT_TYPE       VARCHAR2(40 CHAR) NOT NULL,
    PAYLOAD             CLOB NOT NULL,
    CREATED_AT          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_EVAL_SNAPSHOT_PLAN
        FOREIGN KEY (PLAN_ID) REFERENCES EIMS_EVALUATION_PLAN(ID),
    CONSTRAINT CK_EVAL_SNAPSHOT_IDEA_VERSION
        CHECK (IDEA_VERSION >= 1),
    CONSTRAINT CK_EVAL_SNAPSHOT_PAYLOAD_JSON
        CHECK (PAYLOAD IS JSON),
    CONSTRAINT PK_EVALUATION_SNAPSHOT PRIMARY KEY (ID)
);

CREATE INDEX IX_EVAL_SNAPSHOT_PLAN
    ON EIMS_EVALUATION_SNAPSHOT (PLAN_ID);

CREATE UNIQUE INDEX UQ_EVAL_SNAPSHOT_PLAN_TYPE
    ON EIMS_EVALUATION_SNAPSHOT (PLAN_ID, SNAPSHOT_TYPE);

-- Evaluation snapshots are frozen evidence, not mutable working state.
CREATE OR REPLACE TRIGGER TRG_EVAL_SNAPSHOT_IMMUTABLE
BEFORE UPDATE OR DELETE ON EIMS_EVALUATION_SNAPSHOT
FOR EACH ROW
BEGIN
    RAISE_APPLICATION_ERROR(-20031, 'Evaluation snapshot is immutable');
END;
/

-- Generic optimistic-concurrency predicates are enforced by the application/adapter.
-- These grants preserve owner/application-account separation.
GRANT SELECT, INSERT, UPDATE ON EIMS_EVALUATION_PLAN TO EIMS_APP;
GRANT SELECT, INSERT, UPDATE ON EIMS_EVALUATION_ASSIGNMENT TO EIMS_APP;
GRANT SELECT, INSERT ON EIMS_EVALUATION_SNAPSHOT TO EIMS_APP;

COMMIT;
