-- EIMS S1b-1 v2 / ACR-S2b — Evaluation Core (aligned field-by-field with the C# envelopes)
-- Scope: Evaluation Plan + Assignment (mirror EvaluationPlanEnvelope / EvaluationAssignmentEnvelope) + immutable Evaluation Snapshot.
-- Run as EIMS_OWNER inside FREEPDB1. State vocabularies are owned by the domain code, not by DB CHECKs
-- (the code uses e.g. READY_FOR_G04_DECISION, which the former CHECK list rejected).

CREATE TABLE EIMS_EVALUATION_PLAN (
    ID                         VARCHAR2(100 CHAR) NOT NULL,
    IDEA_ID                    VARCHAR2(128 CHAR) NOT NULL,
    IDEA_VERSION               NUMBER(19)         NOT NULL,
    PLAN_VERSION               NUMBER(10)         NOT NULL,   -- version of the plan definition (envelope PlanVersion)
    STATE                      VARCHAR2(60 CHAR)  NOT NULL,
    CORRELATION_ID             VARCHAR2(128 CHAR) NOT NULL,
    READY_AT                   TIMESTAMP(6) WITH TIME ZONE,
    DECISION_ROUTE             VARCHAR2(120 CHAR),
    DECISION_ROUTE_KIND        VARCHAR2(60 CHAR),
    DECISION_METHOD            VARCHAR2(60 CHAR),
    GOVERNANCE_PROFILE_ID      VARCHAR2(120 CHAR),
    GOVERNANCE_PROFILE_VERSION VARCHAR2(60 CHAR),
    ENTITY_VERSION             NUMBER(10) DEFAULT 1 NOT NULL, -- row concurrency token (used from S2c)
    CREATED_AT                 TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UPDATED_AT                 TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EVALUATION_PLAN PRIMARY KEY (ID),
    CONSTRAINT UQ_EVAL_PLAN_IDEA_VERSION UNIQUE (IDEA_ID, IDEA_VERSION),
    CONSTRAINT CK_EVAL_PLAN_IDEA_VERSION CHECK (IDEA_VERSION >= 1),
    CONSTRAINT CK_EVAL_PLAN_PLAN_VERSION CHECK (PLAN_VERSION >= 1),
    CONSTRAINT CK_EVAL_PLAN_ENTITY_VERSION CHECK (ENTITY_VERSION >= 1)
);

CREATE TABLE EIMS_EVALUATION_ASSIGNMENT (
    ID                        VARCHAR2(100 CHAR) NOT NULL,
    PLAN_ID                   VARCHAR2(100 CHAR) NOT NULL,
    IDEA_ID                   VARCHAR2(128 CHAR) NOT NULL,
    IDEA_VERSION              NUMBER(19)         NOT NULL,
    ROLE_CODE                 VARCHAR2(60 CHAR)  NOT NULL,
    SCOPE_CODE                VARCHAR2(128 CHAR) NOT NULL,
    REQUIRED_FLAG             NUMBER(1) DEFAULT 1 NOT NULL,
    STATE                     VARCHAR2(60 CHAR)  NOT NULL,
    CORRELATION_ID            VARCHAR2(128 CHAR) NOT NULL,
    ENTITY_VERSION            NUMBER(10) DEFAULT 1 NOT NULL,  -- envelope AssignmentVersion
    COMPLETED_AT              TIMESTAMP(6) WITH TIME ZONE,
    COMPLETED_BY_PERSON_ID    VARCHAR2(64 CHAR),
    AUTHORITY_ASSIGNMENT_ID   VARCHAR2(128 CHAR),
    ASSESSMENT_SCHEMA_ID      VARCHAR2(120 CHAR),
    ASSESSMENT_SCHEMA_VERSION VARCHAR2(60 CHAR),
    ASSESSMENT_OUTCOME        VARCHAR2(100 CHAR),
    CREATED_AT                TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UPDATED_AT                TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EVALUATION_ASSIGNMENT PRIMARY KEY (ID),
    CONSTRAINT FK_EVAL_ASSIGN_PLAN FOREIGN KEY (PLAN_ID) REFERENCES EIMS_EVALUATION_PLAN (ID),
    CONSTRAINT CK_EVAL_ASSIGN_REQUIRED CHECK (REQUIRED_FLAG IN (0,1)),
    CONSTRAINT CK_EVAL_ASSIGN_VERSION CHECK (ENTITY_VERSION >= 1)
);
CREATE INDEX IX_EVAL_ASSIGN_PLAN_STATE ON EIMS_EVALUATION_ASSIGNMENT (PLAN_ID, STATE);
CREATE INDEX IX_EVAL_ASSIGN_PERSON ON EIMS_EVALUATION_ASSIGNMENT (COMPLETED_BY_PERSON_ID, STATE);

CREATE TABLE EIMS_EVALUATION_SNAPSHOT (
    ID                  VARCHAR2(100 CHAR) NOT NULL,
    PLAN_ID             VARCHAR2(100 CHAR) NOT NULL,
    IDEA_ID             VARCHAR2(100 CHAR) NOT NULL,
    IDEA_VERSION        NUMBER(10) NOT NULL,
    SNAPSHOT_TYPE       VARCHAR2(40 CHAR) NOT NULL,
    PAYLOAD             CLOB NOT NULL,
    CREATED_AT          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_EVAL_SNAPSHOT_PLAN
        FOREIGN KEY (PLAN_ID) REFERENCES EIMS_EVALUATION_PLAN(ID),
    CONSTRAINT CK_EVAL_SNAPSHOT_IDEA_VERSION
        CHECK (IDEA_VERSION >= 1),
    CONSTRAINT CK_EVAL_SNAPSHOT_PAYLOAD_JSON
        CHECK (PAYLOAD IS JSON),
    CONSTRAINT PK_EVALUATION_SNAPSHOT PRIMARY KEY (ID)
);

CREATE INDEX IX_EVAL_SNAPSHOT_PLAN
    ON EIMS_EVALUATION_SNAPSHOT (PLAN_ID);

CREATE UNIQUE INDEX UQ_EVAL_SNAPSHOT_PLAN_TYPE
    ON EIMS_EVALUATION_SNAPSHOT (PLAN_ID, SNAPSHOT_TYPE);

-- Evaluation snapshots are frozen evidence, not mutable working state.
CREATE OR REPLACE TRIGGER TRG_EVAL_SNAPSHOT_IMMUTABLE
BEFORE UPDATE OR DELETE ON EIMS_EVALUATION_SNAPSHOT
FOR EACH ROW
BEGIN
    RAISE_APPLICATION_ERROR(-20031, 'Evaluation snapshot is immutable');
END;
/

-- Generic optimistic-concurrency predicates are enforced by the application/adapter.
-- These grants preserve owner/application-account separation.
GRANT SELECT, INSERT, UPDATE ON EIMS_EVALUATION_PLAN TO EIMS_APP;
GRANT SELECT, INSERT, UPDATE ON EIMS_EVALUATION_ASSIGNMENT TO EIMS_APP;
GRANT SELECT, INSERT ON EIMS_EVALUATION_SNAPSHOT TO EIMS_APP;

COMMIT;
