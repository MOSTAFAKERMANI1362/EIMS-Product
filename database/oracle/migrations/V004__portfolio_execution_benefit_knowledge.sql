-- EIMS S2f-3 / ACR-S2f3 (builds on ACR-S2f1, ACR-S2f2) — Portfolio thread + Execution + Benefit + Knowledge.
-- Portfolio thread tables mirror PortfolioThreadEnvelope (candidate, assignment, membership, recommendation, execution handoff).
-- EIMS_EXECUTION carries the FULL Wave 10 execution envelope: the portfolio hand-off inserts the row (lifecycle columns defaulted),
-- the Execution store (S2f-2) updates the same row — one entity, one table. Benefit and Knowledge are realigned in S2f-3.

-- Portfolio thread root. THREAD_VERSION is the optimistic-concurrency token of the whole thread; ENTITY_VERSION = envelope Version.
CREATE TABLE EIMS_PORTFOLIO_CANDIDATE (
    ID                    VARCHAR2(100 CHAR) NOT NULL,
    IDEA_ID               VARCHAR2(128 CHAR) NOT NULL,
    APPROVED_IDEA_VERSION NUMBER(19)         NOT NULL,
    STATE                 VARCHAR2(60 CHAR)  NOT NULL,
    ENTITY_VERSION        NUMBER(19)         NOT NULL,
    THREAD_VERSION        NUMBER(19)         NOT NULL,
    CORRELATION_ID        VARCHAR2(128 CHAR) NOT NULL,
    CREATED_AT            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UPDATED_AT            TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PORTFOLIO_CANDIDATE PRIMARY KEY (ID),
    CONSTRAINT UQ_PORT_CAND_IDEA_VERSION UNIQUE (IDEA_ID, APPROVED_IDEA_VERSION),
    CONSTRAINT CK_PORT_CAND_THREAD CHECK (THREAD_VERSION >= 1)
);

CREATE TABLE EIMS_PORTFOLIO_ASSIGNMENT (
    ID             VARCHAR2(100 CHAR) NOT NULL,
    CANDIDATE_ID   VARCHAR2(100 CHAR) NOT NULL,
    PORTFOLIO_ID   VARCHAR2(100 CHAR) NOT NULL,
    STATE          VARCHAR2(60 CHAR)  NOT NULL,
    ENTITY_VERSION NUMBER(19)         NOT NULL,
    CORRELATION_ID VARCHAR2(128 CHAR) NOT NULL,
    CREATED_AT     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UPDATED_AT     TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PORTFOLIO_ASSIGNMENT PRIMARY KEY (ID),
    CONSTRAINT UQ_PORT_ASSIGN_CANDIDATE UNIQUE (CANDIDATE_ID),
    CONSTRAINT FK_PORT_ASSIGN_CANDIDATE FOREIGN KEY (CANDIDATE_ID) REFERENCES EIMS_PORTFOLIO_CANDIDATE (ID)
);

CREATE TABLE EIMS_PORTFOLIO_MEMBERSHIP (
    ID                      VARCHAR2(100 CHAR) NOT NULL,
    CANDIDATE_ID            VARCHAR2(100 CHAR) NOT NULL,
    ASSIGNMENT_ID           VARCHAR2(100 CHAR) NOT NULL,
    PORTFOLIO_ID            VARCHAR2(100 CHAR) NOT NULL,
    STATUS                  VARCHAR2(60 CHAR)  NOT NULL,
    ENTITY_VERSION          NUMBER(19)         NOT NULL,
    DECIDED_BY_PERSON_ID    VARCHAR2(64 CHAR)  NOT NULL,
    AUTHORITY_ASSIGNMENT_ID VARCHAR2(128 CHAR) NOT NULL,
    CORRELATION_ID          VARCHAR2(128 CHAR) NOT NULL,
    DECIDED_AT              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UPDATED_AT              TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PORTFOLIO_MEMBERSHIP PRIMARY KEY (ID),
    CONSTRAINT UQ_PORT_MEMBER_CANDIDATE UNIQUE (CANDIDATE_ID),
    CONSTRAINT FK_PORT_MEMBER_CANDIDATE FOREIGN KEY (CANDIDATE_ID) REFERENCES EIMS_PORTFOLIO_CANDIDATE (ID),
    CONSTRAINT FK_PORT_MEMBER_ASSIGN FOREIGN KEY (ASSIGNMENT_ID) REFERENCES EIMS_PORTFOLIO_ASSIGNMENT (ID)
);

CREATE TABLE EIMS_EXECUTION_RECOMMENDATION (
    ID                      VARCHAR2(100 CHAR) NOT NULL,
    CANDIDATE_ID            VARCHAR2(100 CHAR) NOT NULL,
    MEMBERSHIP_ID           VARCHAR2(100 CHAR) NOT NULL,
    STATE                   VARCHAR2(60 CHAR)  NOT NULL,
    ENTITY_VERSION          NUMBER(19)         NOT NULL,
    GOVERNANCE_DECISION_REF VARCHAR2(200 CHAR),
    BASELINE_APPROVED       NUMBER(1) DEFAULT 0 NOT NULL,
    APPROVED_BASELINE_REF   VARCHAR2(200 CHAR),
    CORRELATION_ID          VARCHAR2(128 CHAR) NOT NULL,
    CREATED_AT              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UPDATED_AT              TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EXECUTION_RECOMMENDATION PRIMARY KEY (ID),
    CONSTRAINT UQ_EXEC_REC_CANDIDATE UNIQUE (CANDIDATE_ID),
    CONSTRAINT FK_EXEC_REC_CANDIDATE FOREIGN KEY (CANDIDATE_ID) REFERENCES EIMS_PORTFOLIO_CANDIDATE (ID),
    CONSTRAINT FK_EXEC_REC_MEMBERSHIP FOREIGN KEY (MEMBERSHIP_ID) REFERENCES EIMS_PORTFOLIO_MEMBERSHIP (ID),
    CONSTRAINT CK_EXEC_REC_BASELINE CHECK (BASELINE_APPROVED IN (0,1))
);

-- One execution entity: created by the portfolio hand-off, then managed by the Execution store (mirrors ExecutionEnvelopeWave10).
CREATE TABLE EIMS_EXECUTION (
    ID                                    VARCHAR2(100 CHAR) NOT NULL,
    RECOMMENDATION_ID                     VARCHAR2(100 CHAR) NOT NULL,
    CANDIDATE_ID                          VARCHAR2(100 CHAR) NOT NULL,
    IDEA_ID                               VARCHAR2(128 CHAR) NOT NULL,
    APPROVED_IDEA_VERSION                 NUMBER(19)         NOT NULL,
    STATE                                 VARCHAR2(60 CHAR)  NOT NULL,
    ENTITY_VERSION                        NUMBER(19)         NOT NULL,
    CHARTER_APPROVED                      NUMBER(1) DEFAULT 0 NOT NULL,
    PLAN_APPROVED                         NUMBER(1) DEFAULT 0 NOT NULL,
    PROGRESS_PERCENT                      NUMBER(3) DEFAULT 0 NOT NULL,
    COMPLETION_DOSSIER_REF                VARCHAR2(200 CHAR),
    COMPLETION_APPROVED                   NUMBER(1) DEFAULT 0 NOT NULL,
    COMPLETION_SUBMITTED_BY_PERSON_ID     VARCHAR2(64 CHAR),
    COMPLETION_SUBMITTED_BY_ASSIGNMENT_ID VARCHAR2(128 CHAR),
    COMPLETION_REVIEWED_BY_PERSON_ID      VARCHAR2(64 CHAR),
    COMPLETION_REVIEW_DECISION            VARCHAR2(60 CHAR),
    BENEFIT_ID                            VARCHAR2(100 CHAR),
    CORRELATION_ID                        VARCHAR2(128 CHAR) NOT NULL,
    CREATED_AT                            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UPDATED_AT                            TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EXECUTION PRIMARY KEY (ID),
    CONSTRAINT UQ_EXEC_RECOMMENDATION UNIQUE (RECOMMENDATION_ID),
    CONSTRAINT UQ_EXEC_CANDIDATE UNIQUE (CANDIDATE_ID),
    CONSTRAINT FK_EXEC_RECOMMENDATION FOREIGN KEY (RECOMMENDATION_ID) REFERENCES EIMS_EXECUTION_RECOMMENDATION (ID),
    CONSTRAINT FK_EXEC_CANDIDATE FOREIGN KEY (CANDIDATE_ID) REFERENCES EIMS_PORTFOLIO_CANDIDATE (ID),
    CONSTRAINT CK_EXEC_FLAGS CHECK (CHARTER_APPROVED IN (0,1) AND PLAN_APPROVED IN (0,1) AND COMPLETION_APPROVED IN (0,1)),
    CONSTRAINT CK_EXEC_PROGRESS CHECK (PROGRESS_PERCENT BETWEEN 0 AND 100)
);
CREATE INDEX IX_EXEC_STATE ON EIMS_EXECUTION (STATE);

-- One benefit entity: the Execution completion INSERTs the obligation (subset of the columns), the Benefit store (S2f-3) updates the same row.
-- Mirrors BenefitEnvelopeWave11; the obligation view is BenefitObligationEnvelopeWave10. State vocabulary is owned by the domain code.
CREATE TABLE EIMS_BENEFIT (
    ID                      VARCHAR2(100 CHAR) NOT NULL,
    EXECUTION_ID            VARCHAR2(100 CHAR) NOT NULL,
    IDEA_ID                 VARCHAR2(128 CHAR) NOT NULL,
    APPROVED_IDEA_VERSION   NUMBER(19)         NOT NULL,
    STATE                   VARCHAR2(60 CHAR)  NOT NULL,
    ENTITY_VERSION          NUMBER(19)         NOT NULL,
    BASELINE_EVIDENCE_REF   VARCHAR2(200 CHAR),
    TARGET_EVIDENCE_REF     VARCHAR2(200 CHAR),
    MEASUREMENT_PLAN_REF    VARCHAR2(200 CHAR),
    MEASUREMENT_DOSSIER_REF VARCHAR2(200 CHAR),
    VERIFICATION_DOSSIER_REF VARCHAR2(200 CHAR),
    ATTRIBUTION_DOSSIER_REF VARCHAR2(200 CHAR),
    REALIZATION_DOSSIER_REF VARCHAR2(200 CHAR),
    ACCEPTED_BY_PERSON_ID   VARCHAR2(64 CHAR),
    ACCEPTED_BY_ASSIGNMENT_ID VARCHAR2(128 CHAR),
    MEASURED_BY_PERSON_ID   VARCHAR2(64 CHAR),
    VERIFIED_BY_PERSON_ID   VARCHAR2(64 CHAR),
    KNOWLEDGE_ID            VARCHAR2(100 CHAR),
    CORRELATION_ID          VARCHAR2(128 CHAR) NOT NULL,
    CREATED_AT              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UPDATED_AT              TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_BENEFIT PRIMARY KEY (ID),
    CONSTRAINT UQ_BEN_EXECUTION UNIQUE (EXECUTION_ID),
    CONSTRAINT FK_BEN_EXECUTION FOREIGN KEY (EXECUTION_ID) REFERENCES EIMS_EXECUTION (ID)
);

-- Knowledge asset, one per benefit (mirrors KnowledgeEnvelopeWave13). State vocabulary is owned by the domain code.
CREATE TABLE EIMS_KNOWLEDGE_ASSET (
    ID                         VARCHAR2(100 CHAR) NOT NULL,
    BENEFIT_ID                 VARCHAR2(100 CHAR) NOT NULL,
    EXECUTION_ID               VARCHAR2(100 CHAR) NOT NULL,
    IDEA_ID                    VARCHAR2(128 CHAR) NOT NULL,
    APPROVED_IDEA_VERSION      NUMBER(19)         NOT NULL,
    STATE                      VARCHAR2(60 CHAR)  NOT NULL,
    ENTITY_VERSION             NUMBER(19)         NOT NULL,
    AUTHOR_PERSON_ID           VARCHAR2(64 CHAR)  NOT NULL,
    AUTHOR_ASSIGNMENT_ID       VARCHAR2(128 CHAR) NOT NULL,
    AUTHOR_POLICY              VARCHAR2(120 CHAR) NOT NULL,
    SCOPE_CODE                 VARCHAR2(128 CHAR) NOT NULL,
    VALIDATED_BY_PERSON_ID     VARCHAR2(64 CHAR),
    VALIDATED_BY_ASSIGNMENT_ID VARCHAR2(128 CHAR),
    PUBLISHED_BY_PERSON_ID     VARCHAR2(64 CHAR),
    PUBLISHED_BY_ASSIGNMENT_ID VARCHAR2(128 CHAR),
    PUBLICATION_DOSSIER_REF    VARCHAR2(200 CHAR),
    CORRELATION_ID             VARCHAR2(128 CHAR) NOT NULL,
    CREATED_AT                 TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UPDATED_AT                 TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_KNOWLEDGE_ASSET PRIMARY KEY (ID),
    CONSTRAINT UQ_KNOWLEDGE_BENEFIT UNIQUE (BENEFIT_ID),
    CONSTRAINT FK_KNOWLEDGE_BENEFIT FOREIGN KEY (BENEFIT_ID) REFERENCES EIMS_BENEFIT (ID)
);

