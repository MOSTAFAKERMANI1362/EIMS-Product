  END;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM user_tables
   WHERE table_name IN ('EIMS_G04_ASSESSMENT','EIMS_G04_COMMITTEE_SNAPSHOT','EIMS_G04_COMMITTEE_STATE','EIMS_G04_VOTE_REVISION','EIMS_G04_EFFECTIVE_VOTE','EIMS_G04_FINAL_DECISION');
