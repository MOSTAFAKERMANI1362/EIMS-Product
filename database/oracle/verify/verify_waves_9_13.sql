SET SERVEROUTPUT ON
SET VERIFY OFF
DECLARE
  v_cnt NUMBER;
  v_rows NUMBER;
  PROCEDURE rep(p_name VARCHAR2, p_ok BOOLEAN) IS
  BEGIN DBMS_OUTPUT.PUT_LINE(CASE WHEN p_ok THEN 'PASS ' ELSE 'FAIL ' END || p_name); END;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM user_tables WHERE table_name IN (
    'EIMS_PORTFOLIO_CANDIDATE','EIMS_PORTFOLIO_ASSIGNMENT','EIMS_PORTFOLIO_MEMBERSHIP',
    'EIMS_EXECUTION_RECOMMENDATION','EIMS_EXECUTION','EIMS_BENEFIT','EIMS_KNOWLEDGE_ASSET');
