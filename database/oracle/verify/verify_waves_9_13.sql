-- EIMS S2f-1 verification of V004 (portfolio thread, execution entity, benefit, knowledge). Run as EIMS_OWNER. Rows are rolled back.
SET SERVEROUTPUT ON
SET VERIFY OFF
DECLARE
  v_cnt NUMBER;
  v_rows NUMBER;
  PROCEDURE rep(p_name VARCHAR2, p_ok BOOLEAN) IS
  BEGIN DBMS_OUTPUT.PUT_LINE(CASE WHEN p_ok THEN 'PASS ' ELSE 'FAIL ' END || p_name); END;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM user_tables WHERE table_name IN (
    'EIMS_PORTFOLIO_CANDIDATE','EIMS_PORTFOLIO_ASSIGNMENT','EIMS_PORTFOLIO_MEMBERSHIP',
    'EIMS_EXECUTION_RECOMMENDATION','EIMS_EXECUTION','EIMS_BENEFIT','EIMS_KNOWLEDGE_ASSET');
  rep('7 downstream tables exist', v_cnt = 7);

  INSERT INTO EIMS_PORTFOLIO_CANDIDATE (ID, IDEA_ID, APPROVED_IDEA_VERSION, STATE, ENTITY_VERSION, THREAD_VERSION, CORRELATION_ID, CREATED_AT)
  VALUES ('T-CAND-1', 'T-IDEA-DOWN', 1, 'UNASSIGNED_CANDIDATE', 1, 1, 'C-T', SYSTIMESTAMP);
  INSERT INTO EIMS_PORTFOLIO_ASSIGNMENT (ID, CANDIDATE_ID, PORTFOLIO_ID, STATE, ENTITY_VERSION, CORRELATION_ID, CREATED_AT)
  VALUES ('T-ASG-1', 'T-CAND-1', 'PF-1', 'ASSIGNED', 1, 'C-T', SYSTIMESTAMP);
  INSERT INTO EIMS_PORTFOLIO_MEMBERSHIP (ID, CANDIDATE_ID, ASSIGNMENT_ID, PORTFOLIO_ID, STATUS, ENTITY_VERSION, DECIDED_BY_PERSON_ID, AUTHORITY_ASSIGNMENT_ID, CORRELATION_ID, DECIDED_AT)
  VALUES ('T-MEM-1', 'T-CAND-1', 'T-ASG-1', 'PF-1', 'ACCEPTED', 1, 'P1', 'ASG-1', 'C-T', SYSTIMESTAMP);
  INSERT INTO EIMS_EXECUTION_RECOMMENDATION (ID, CANDIDATE_ID, MEMBERSHIP_ID, STATE, ENTITY_VERSION, BASELINE_APPROVED, CORRELATION_ID, CREATED_AT)
  VALUES ('T-REC-1', 'T-CAND-1', 'T-MEM-1', 'APPROVED', 1, 1, 'C-T', SYSTIMESTAMP);
  INSERT INTO EIMS_EXECUTION (ID, RECOMMENDATION_ID, CANDIDATE_ID, IDEA_ID, APPROVED_IDEA_VERSION, STATE, ENTITY_VERSION, CORRELATION_ID, CREATED_AT)
  VALUES ('T-EXEC-1', 'T-REC-1', 'T-CAND-1', 'T-IDEA-DOWN', 1, 'HANDOFF_PENDING', 1, 'C-T', SYSTIMESTAMP);
  INSERT INTO EIMS_BENEFIT (ID, EXECUTION_ID, IDEA_ID, APPROVED_IDEA_VERSION, STATE, ENTITY_VERSION, CORRELATION_ID, CREATED_AT)
  VALUES ('T-BEN-1', 'T-EXEC-1', 'T-IDEA-DOWN', 1, 'OBLIGATION_PENDING_ACCEPTANCE', 1, 'C-T', SYSTIMESTAMP);
  INSERT INTO EIMS_KNOWLEDGE_ASSET (ID, BENEFIT_ID, EXECUTION_ID, IDEA_ID, APPROVED_IDEA_VERSION, STATE, ENTITY_VERSION, AUTHOR_PERSON_ID,
         AUTHOR_ASSIGNMENT_ID, AUTHOR_POLICY, SCOPE_CODE, CORRELATION_ID, CREATED_AT, UPDATED_AT)
  VALUES ('T-KNOW-1', 'T-BEN-1', 'T-EXEC-1', 'T-IDEA-DOWN', 1, 'DRAFT', 1, 'P1', 'ASG-1', 'AUTHOR_POLICY', 'SCOPE-A', 'C-T', SYSTIMESTAMP, SYSTIMESTAMP);
   SELECT COUNT(*)
    INTO v_cnt
    FROM EIMS_PORTFOLIO_CANDIDATE c
    JOIN EIMS_PORTFOLIO_ASSIGNMENT a
      ON a.CANDIDATE_ID = c.ID
    JOIN EIMS_PORTFOLIO_MEMBERSHIP m
      ON m.CANDIDATE_ID = c.ID
     AND m.ASSIGNMENT_ID = a.ID
    JOIN EIMS_EXECUTION_RECOMMENDATION r
      ON r.CANDIDATE_ID = c.ID
     AND r.MEMBERSHIP_ID = m.ID
    JOIN EIMS_EXECUTION e
      ON e.CANDIDATE_ID = c.ID
     AND e.RECOMMENDATION_ID = r.ID
     AND e.IDEA_ID = c.IDEA_ID
     AND e.APPROVED_IDEA_VERSION = c.APPROVED_IDEA_VERSION
    JOIN EIMS_BENEFIT b
      ON b.EXECUTION_ID = e.ID
     AND b.IDEA_ID = e.IDEA_ID
     AND b.APPROVED_IDEA_VERSION = e.APPROVED_IDEA_VERSION
    JOIN EIMS_KNOWLEDGE_ASSET k
      ON k.BENEFIT_ID = b.ID
     AND k.EXECUTION_ID = e.ID
     AND k.IDEA_ID = b.IDEA_ID
     AND k.APPROVED_IDEA_VERSION = b.APPROVED_IDEA_VERSION
   WHERE c.ID = 'T-CAND-1'
     AND a.ID = 'T-ASG-1'
     AND m.ID = 'T-MEM-1'
     AND r.ID = 'T-REC-1'
     AND e.ID = 'T-EXEC-1'
     AND b.ID = 'T-BEN-1'
     AND k.ID = 'T-KNOW-1';

  rep(
    'portfolio thread -> execution -> benefit -> knowledge chain is consistent',
    v_cnt = 1
  );

  BEGIN
    INSERT INTO EIMS_PORTFOLIO_CANDIDATE (ID, IDEA_ID, APPROVED_IDEA_VERSION, STATE, ENTITY_VERSION, THREAD_VERSION, CORRELATION_ID, CREATED_AT)
    VALUES ('T-CAND-2', 'T-IDEA-DOWN', 1, 'UNASSIGNED_CANDIDATE', 1, 1, 'C-T', SYSTIMESTAMP);
    rep('one candidate per idea version enforced', FALSE);
  EXCEPTION WHEN DUP_VAL_ON_INDEX THEN rep('one candidate per idea version enforced', TRUE); END;

  UPDATE EIMS_PORTFOLIO_CANDIDATE SET THREAD_VERSION = 2 WHERE ID = 'T-CAND-1' AND THREAD_VERSION = 1;
  v_rows := SQL%ROWCOUNT;
  rep('optimistic thread update with correct version changes 1 row', v_rows = 1);
  UPDATE EIMS_PORTFOLIO_CANDIDATE SET THREAD_VERSION = 3 WHERE ID = 'T-CAND-1' AND THREAD_VERSION = 1;
  v_rows := SQL%ROWCOUNT;
  rep('stale thread version changes 0 rows (conflict detected)', v_rows = 0);

  BEGIN
    INSERT INTO EIMS_PORTFOLIO_MEMBERSHIP (ID, CANDIDATE_ID, ASSIGNMENT_ID, PORTFOLIO_ID, STATUS, ENTITY_VERSION, DECIDED_BY_PERSON_ID, AUTHORITY_ASSIGNMENT_ID, CORRELATION_ID, DECIDED_AT)
    VALUES ('T-MEM-2', 'T-CAND-1', 'T-ASG-1', 'PF-1', 'ACCEPTED', 1, 'P1', 'ASG-1', 'C-T', SYSTIMESTAMP);
    rep('one membership per candidate enforced', FALSE);
  EXCEPTION WHEN DUP_VAL_ON_INDEX THEN rep('one membership per candidate enforced', TRUE); END;
  BEGIN
    INSERT INTO EIMS_EXECUTION_RECOMMENDATION (ID, CANDIDATE_ID, MEMBERSHIP_ID, STATE, ENTITY_VERSION, BASELINE_APPROVED, CORRELATION_ID, CREATED_AT)
    VALUES ('T-REC-2', 'T-CAND-1', 'T-MEM-1', 'APPROVED', 1, 1, 'C-T', SYSTIMESTAMP);
    rep('one recommendation per candidate enforced', FALSE);
  EXCEPTION WHEN DUP_VAL_ON_INDEX THEN rep('one recommendation per candidate enforced', TRUE); END;
  BEGIN
    INSERT INTO EIMS_EXECUTION (ID, RECOMMENDATION_ID, CANDIDATE_ID, IDEA_ID, APPROVED_IDEA_VERSION, STATE, ENTITY_VERSION, CORRELATION_ID, CREATED_AT)
    VALUES ('T-EXEC-2', 'T-REC-1', 'T-CAND-1', 'T-IDEA-DOWN', 1, 'HANDOFF_PENDING', 1, 'C-T', SYSTIMESTAMP);
    rep('one execution per recommendation enforced', FALSE);
  EXCEPTION WHEN DUP_VAL_ON_INDEX THEN rep('one execution per recommendation enforced', TRUE); END;
  BEGIN
    INSERT INTO EIMS_BENEFIT (ID, EXECUTION_ID, IDEA_ID, APPROVED_IDEA_VERSION, STATE, ENTITY_VERSION, CORRELATION_ID, CREATED_AT)
    VALUES ('T-BEN-2', 'T-EXEC-1', 'T-IDEA-DOWN', 1, 'OBLIGATION_PENDING_ACCEPTANCE', 1, 'C-T', SYSTIMESTAMP);
    rep('one benefit per execution enforced', FALSE);
  EXCEPTION WHEN DUP_VAL_ON_INDEX THEN rep('one benefit per execution enforced', TRUE); END;
  BEGIN
    INSERT INTO EIMS_KNOWLEDGE_ASSET (ID, BENEFIT_ID, EXECUTION_ID, IDEA_ID, APPROVED_IDEA_VERSION, STATE, ENTITY_VERSION, AUTHOR_PERSON_ID,
           AUTHOR_ASSIGNMENT_ID, AUTHOR_POLICY, SCOPE_CODE, CORRELATION_ID, CREATED_AT, UPDATED_AT)
    VALUES ('T-KNOW-2', 'T-BEN-1', 'T-EXEC-1', 'T-IDEA-DOWN', 1, 'DRAFT', 1, 'P1', 'ASG-1', 'AUTHOR_POLICY', 'SCOPE-A', 'C-T', SYSTIMESTAMP, SYSTIMESTAMP);
    rep('one Knowledge Asset per Benefit enforced', FALSE);
  EXCEPTION WHEN DUP_VAL_ON_INDEX THEN rep('one Knowledge Asset per Benefit enforced', TRUE); END;

  ROLLBACK;
  DBMS_OUTPUT.PUT_LINE('Test rows rolled back.');
END;
