    UPDATE EIMS_BENEFIT SET STATUS = 'REALIZED_NOW' WHERE ID = 'T-BEN-1';
    rep('invalid Benefit state rejected', FALSE);
  EXCEPTION WHEN OTHERS THEN rep('invalid Benefit state rejected', SQLCODE = -2290); END;
  BEGIN
    INSERT INTO EIMS_KNOWLEDGE_ASSET (ID, BENEFIT_ID, TITLE) VALUES ('T-KNOW-2', 'T-BEN-1', 'Second Knowledge');
    rep('one Knowledge Asset per Benefit enforced', FALSE);
  EXCEPTION WHEN DUP_VAL_ON_INDEX THEN rep('one Knowledge Asset per Benefit enforced', TRUE); END;

  ROLLBACK;
  DBMS_OUTPUT.PUT_LINE('Test rows rolled back.');
END;
