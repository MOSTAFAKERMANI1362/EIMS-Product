  INSERT INTO EIMS_PORTFOLIO_CANDIDATE (ID, IDEA_ID, APPROVED_IDEA_VERSION, STATE, ENTITY_VERSION, THREAD_VERSION, CORRELATION_ID, CREATED_AT)
